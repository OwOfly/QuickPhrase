# Shared isolation for Windows smoke tests. Fresh portable data and logs are
# retained for inspection; only processes started by this run are stopped.
function Assert-QPTestIdle {
    $mutex = $null
    $exists = [Threading.Mutex]::TryOpenExisting('Local\QuickPhrase.SingleInstance', [ref]$mutex)
    if ($exists) { $mutex.Dispose() }
    if ($exists -or (Get-Process -Name quickphrase -ErrorAction SilentlyContinue)) {
        throw 'QuickPhrase is running. Close it normally before running this test.'
    }
}

function New-QPTestRun([string]$SourceExe) {
    Assert-QPTestIdle
    $dir = Join-Path ([IO.Path]::GetTempPath()) ('quickphrase-smoke-' + [Guid]::NewGuid())
    New-Item -ItemType Directory -Path $dir | Out-Null
    $exe = Join-Path $dir 'quickphrase.exe'
    Copy-Item -LiteralPath $SourceExe -Destination $exe
    [IO.File]::WriteAllText((Join-Path $dir 'portable.txt'), '')
    $data = Join-Path $dir 'data'
    New-Item -ItemType Directory -Path $data | Out-Null
    Write-Host "Isolated smoke data: $dir"
    Write-Host "Source EXE: $SourceExe"
    Write-Host ("Source SHA256: " + (Get-FileHash $SourceExe -Algorithm SHA256).Hash.ToLower())
    [pscustomobject]@{
        Directory = $dir
        Exe = $exe
        Data = $data
        Log = Join-Path $data ('logs\qp-{0}.log' -f (Get-Date -Format 'yyyy-MM-dd'))
        Processes = New-Object 'System.Collections.Generic.List[System.Diagnostics.Process]'
    }
}

function Start-QPTest {
    param(
        [string[]]$Arguments = @(),
        [string]$Probe,
        [switch]$Wait,
        [int]$WakePid = 0,
        [switch]$PanelWithoutInjection,
        [switch]$AllowUnfocusedPanel
    )
    $info = New-Object Diagnostics.ProcessStartInfo
    $info.FileName = if ($Probe) { $Probe } else { $qpRun.Exe }
    # All arguments are switches or file paths generated by the fixture.
    $info.Arguments = ($Arguments | ForEach-Object { '"' + $_ + '"' }) -join ' '
    $info.WorkingDirectory = $qpRun.Directory
    $info.UseShellExecute = $false
    if (-not $Probe) {
        foreach ($key in 'ALLOW_UNFOCUSED_PANEL', 'NO_INJECT', 'NO_ANIMATION') {
            $info.EnvironmentVariables.Remove("QUICKPHRASE_TEST_$key")
        }
        $info.EnvironmentVariables['QUICKPHRASE_TEST_WAKE_PID'] = [string]$WakePid
        if ($PanelWithoutInjection -or $AllowUnfocusedPanel) {
            $info.EnvironmentVariables['QUICKPHRASE_TEST_ALLOW_UNFOCUSED_PANEL'] = '1'
        }
        if ($PanelWithoutInjection) {
            $info.EnvironmentVariables['QUICKPHRASE_TEST_NO_INJECT'] = '1'
            $info.EnvironmentVariables['QUICKPHRASE_TEST_NO_ANIMATION'] = '1'
        }
    }
    $child = [Diagnostics.Process]::Start($info)
    $qpRun.Processes.Add($child)
    if (-not $Probe -and $WakePid -eq 0) { $script:qpTestWindowsPid = $child.Id }
    if ($Wait -and -not $child.WaitForExit(30000)) { throw "Timed out: $($info.FileName) $Arguments" }
    $child
}

function Stop-QPTestProcess([Diagnostics.Process]$Child) {
    if (-not $Child.HasExited) {
        try { $Child.Kill() } catch { if (-not $Child.HasExited) { throw } }
        if (-not $Child.WaitForExit(5000)) { throw "Test process did not exit: $($Child.Id)" }
    }
}

function Stop-QPTestRun {
    foreach ($child in $qpRun.Processes) {
        try { Stop-QPTestProcess $child } catch { Write-Warning $_.Exception.Message }
        $child.Dispose()
    }
}

if (-not ('QPTestNative' -as [type])) {
    Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public static class QPTestNative {
  [DllImport("user32.dll")] public static extern uint GetWindowThreadProcessId(IntPtr window, out uint process);
  [DllImport("user32.dll")] public static extern uint GetClipboardSequenceNumber();
}
"@
}

function Test-QPTestWindow([IntPtr]$Window) {
    [uint32]$windowPid = 0
    [void][QPTestNative]::GetWindowThreadProcessId($Window, [ref]$windowPid)
    $windowPid -ne 0 -and $windowPid -eq $script:qpTestWindowsPid
}

function Wait-Until([scriptblock]$Condition, [int]$TimeoutMs = 3000, [int]$IntervalMs = 50) {
    $deadline = [DateTime]::UtcNow.AddMilliseconds($TimeoutMs)
    while ([DateTime]::UtcNow -lt $deadline) {
        if (& $Condition) { return $true }
        Start-Sleep -Milliseconds $IntervalMs
    }
    return [bool](& $Condition)
}
